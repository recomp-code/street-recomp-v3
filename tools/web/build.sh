#!/bin/sh
# Browser (WebAssembly) build of the port, on a Mac that already ran tools/macos/install.sh.
#   tools/web/build.sh            everything: tools, dependencies, the game, the web folder
#   tools/web/build.sh game       only rebuild the game and refresh the web folder
# The result goes to $NBA_ROOT/web-site (serve it with tools/web/serve.sh).
#
# Pieces (all under $NBA_ROOT, default ~/NBAStreetRecomp):
#   emsdk            Emscripten 6.0.12 (C++ to WebAssembly)
#   wasm-deps        FFmpeg 7.1.2 built for WebAssembly (the game's videos)
#   play             Play! at 83700b2c + patches/play*.patch: its PS2 GS renderer runs on WebGL2
#   PS2Recomp-web    PS2Recomp 2c5fbb9 + patches/ps2recomp.patch + patches/ps2recomp-web.patch,
#                    with the game code generated by install.sh (copied from PS2Recomp)
set -e
ROOT="${NBA_ROOT:-$HOME/NBAStreetRecomp}"
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
LOGS="$ROOT/logs"
SRC="$ROOT/PS2Recomp-web"
SITE="$ROOT/web-site"
EMSDK_VERSION=6.0.12
PLAY_COMMIT=83700b2c31e593bc94e845b4b31b797be84dda59
FFMPEG_VERSION=7.1.2
mkdir -p "$LOGS"
step() { printf '\n==> %s\n' "$1"; }
fail() { tail -30 "$1"; echo "$2 failed: $1"; exit 1; }

[ -f "$ROOT/PS2Recomp/ps2xRuntime/src/runner/nba_street_v3_overrides.cpp" ] \
    || { echo "Run tools/macos/install.sh first: the web build reuses the game code it generates."; exit 1; }

emsdk_env() {
    # shellcheck disable=SC1091
    . "$ROOT/emsdk/emsdk_env.sh" > /dev/null 2>&1
}

tools() {
    step "Emscripten $EMSDK_VERSION"
    [ -d "$ROOT/emsdk/.git" ] || git clone https://github.com/emscripten-core/emsdk.git "$ROOT/emsdk"
    "$ROOT/emsdk/emsdk" install "$EMSDK_VERSION" > "$LOGS/web_emsdk.log" 2>&1 || fail "$LOGS/web_emsdk.log" "emsdk install"
    "$ROOT/emsdk/emsdk" activate "$EMSDK_VERSION" >> "$LOGS/web_emsdk.log" 2>&1
    command -v brotli > /dev/null || brew install brotli
}

ffmpeg() {
    step "FFmpeg $FFMPEG_VERSION for WebAssembly (~10 minutes)"
    [ -f "$ROOT/wasm-deps/prefix/lib/libavcodec.a" ] && { echo "  already built"; return; }
    mkdir -p "$ROOT/wasm-deps/src"
    cd "$ROOT/wasm-deps/src"
    [ -d "ffmpeg-$FFMPEG_VERSION" ] || { curl -fsSL "https://ffmpeg.org/releases/ffmpeg-$FFMPEG_VERSION.tar.xz" | tar xJ; }
    cd "ffmpeg-$FFMPEG_VERSION"
    # Only what the game uses: MPEG-2 video decoding, scaling and resampling.
    emconfigure ./configure --prefix="$ROOT/wasm-deps/prefix" --target-os=none --arch=x86_32 --enable-cross-compile \
        --cc=emcc --cxx=em++ --ar=emar --ranlib=emranlib --nm=emnm \
        --disable-x86asm --disable-inline-asm --disable-asm --disable-stripping --disable-programs --disable-doc \
        --disable-debug --disable-network --disable-autodetect --enable-pthreads --disable-everything \
        --enable-decoder=mpeg2video --enable-parser=mpegvideo --enable-swscale --enable-swresample --enable-avformat \
        --extra-cflags='-O3 -pthread -msimd128' --extra-ldflags=-pthread > "$LOGS/web_ffmpeg.log" 2>&1 \
        || fail "$LOGS/web_ffmpeg.log" "FFmpeg configure"
    make -j"$(sysctl -n hw.ncpu)" install >> "$LOGS/web_ffmpeg.log" 2>&1 || fail "$LOGS/web_ffmpeg.log" "FFmpeg build"
}

play() {
    step "Play! GS renderer (WebGL2)"
    [ -d "$ROOT/play/.git" ] || git clone https://github.com/jpd002/Play-.git "$ROOT/play"
    cd "$ROOT/play"
    git checkout --quiet "$PLAY_COMMIT"
    git submodule update --init --recursive --quiet
    for p in "play.patch:." "play-dependencies.patch:deps/Dependencies" "play-codegen.patch:deps/CodeGen"; do
        patch="${p%%:*}"; dir="${p#*:}"
        git -C "$dir" apply --check --reverse "$REPO/patches/$patch" 2> /dev/null && continue # already applied
        if ! git -C "$dir" apply --check "$REPO/patches/$patch" 2> /dev/null; then
            # An older version of the patch (after a git pull): back to the original files first.
            # Only the files the patch touches; the build folders stay.
            echo "  $patch changed: updating $ROOT/play/$dir"
            git -C "$dir" apply --numstat "$REPO/patches/$patch" | cut -f3 | while read -r f; do
                if git -C "$dir" cat-file -e "HEAD:$f" 2> /dev/null; then git -C "$dir" checkout --quiet HEAD -- "$f"
                else git -C "$dir" rm --quiet --cached --ignore-unmatch -- "$f"; rm -f "$dir/$f"; fi
            done
        fi
        git -C "$dir" apply "$REPO/patches/$patch" || { echo "  $patch does not apply: reset $ROOT/play/$dir (git checkout -- .) and run again"; exit 1; }
    done
    emcmake cmake -S . -B build_wasm -G Ninja -DCMAKE_BUILD_TYPE=Release -DBUILD_PLAY=ON -DBUILD_TESTS=OFF \
        -DBUILD_LIBRETRO_CORE=OFF -DPLAY_WASM_EXCEPTIONS=ON > "$LOGS/web_play.log" 2>&1 || fail "$LOGS/web_play.log" "Play! configure"
    cmake --build build_wasm --target gsh_opengl Framework_OpenGl PlayCore app_shared >> "$LOGS/web_play.log" 2>&1 \
        || fail "$LOGS/web_play.log" "Play! build"
}

sources() {
    step "PS2Recomp for the web (2c5fbb9 + patches)"
    [ -d "$SRC/.git" ] || git clone "$ROOT/PS2Recomp" "$SRC"
    cd "$SRC"
    if ! git apply --check --reverse --whitespace=nowarn "$REPO/patches/ps2recomp-web.patch" 2> /dev/null; then
        git checkout --quiet -f 2c5fbb9
        git clean -fdq -e ps2xRuntime/src/runner -e ps2xRuntime/include
        git apply --whitespace=nowarn "$REPO/patches/ps2recomp.patch"
        git apply --whitespace=nowarn "$REPO/patches/ps2recomp-web.patch"
        echo "  patches applied"
    fi
    # The game code generated from your ELF by install.sh (never part of the repository).
    rsync -a --delete "$ROOT/PS2Recomp/ps2xRuntime/src/runner/" "$SRC/ps2xRuntime/src/runner/"
    for h in ps2_recompiled_functions.h ps2_recompiled_stubs.h; do
        cp "$ROOT/PS2Recomp/ps2xRuntime/include/$h" "$SRC/ps2xRuntime/include/$h"
    done
}

game() {
    step "Game for the browser. The first time takes 1-3 hours"
    cd "$SRC"
    emcmake cmake -S . -B out/build-wasm -G Ninja -DCMAKE_BUILD_TYPE=Release -DPS2X_WASM_TARGET=web \
        -DPS2X_PLAY_ROOT="$ROOT/play" -DPS2X_PLAY_BUILD="$ROOT/play/build_wasm" \
        -DCMAKE_PREFIX_PATH="$ROOT/wasm-deps/prefix" -DCMAKE_EXE_LINKER_FLAGS="-L$ROOT/wasm-deps/prefix/lib" \
        > "$LOGS/web_configure.log" 2>&1 || fail "$LOGS/web_configure.log" "Configure"
    cmake --build out/build-wasm --target ps2EntryRunner > "$LOGS/web_build.log" 2>&1 || {
        grep -E 'error:' "$LOGS/web_build.log" | head -20; fail "$LOGS/web_build.log" "Build"; }
}

site() {
    step "Web folder: $SITE"
    out="$SRC/out/build-wasm/ps2xRuntime"
    mkdir -p "$SITE/data/iso"
    cp "$SRC/ps2xRuntime/web/site/index.html" "$out/ps2EntryRunner.js" "$out/ps2EntryRunner.wasm" "$SITE/"
    # The game code (~370 MB) goes out Brotli-compressed (~27 MB); the server picks the .br copy.
    for f in index.html ps2EntryRunner.js ps2EntryRunner.wasm; do brotli -q 6 -f -o "$SITE/$f.br" "$SITE/$f"; done
    # The disc: read on demand in 1 MB pieces (HTTP Range), never downloaded whole.
    ln -f "$ROOT/game/NBAStreetV3.iso" "$SITE/data/NBAStreetV3.iso" 2> /dev/null || cp "$ROOT/game/NBAStreetV3.iso" "$SITE/data/"
    cp "$ROOT/game/iso/SLUS_211.26" "$ROOT/game/iso/DEV9.IRX" "$SITE/data/iso/"
    # The network configuration the online mode needs, copied onto the memory card once.
    mkdir -p "$SITE/data/mc0/BWNETCNF" && cp "$REPO/game/mc0_netcnf/BWNETCNF/"* "$SITE/data/mc0/BWNETCNF/"
    # HD textures: the fan pack (PCSX2 format), each image read only when the game shows it.
    pack="$ROOT/downloads/NBAStreetV3-HD-Textures.zip"
    [ -f "$pack" ] || { mkdir -p "$ROOT/downloads" && curl -fsSL -o "$pack" \
        https://github.com/recomp-code/street-recomp-v3/releases/download/v1.1/NBAStreetV3-HD-Textures.zip; } || true
    if [ -f "$pack" ]; then
        mkdir -p "$SITE/data/hd" && unzip -q -o "$pack" '*.png' -d "$SITE/data/hd"
        grep -v '^#' "$REPO/gshost/texture_blocklist.txt" > "$SITE/data/hd/.blocklist"
        (cd "$SITE/data/hd" && ls | sed -n 's/\.png$//p' | grep -vxFf .blocklist > index.txt; rm -f .blocklist)
    fi
    echo "  done: tools/web/serve.sh, then open http://localhost:8088"
}

emsdk_env 2> /dev/null || true
case "${1:-all}" in
    all) tools; emsdk_env; ffmpeg; play; sources; game; site ;;
    game) emsdk_env; sources; game; site ;;
    *) sed -n '2,5p' "$0"; exit 1 ;;
esac
